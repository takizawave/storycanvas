export const normalizeLibraryLanguage = language => language === 'en' ? 'en' : 'ja'

export function translateLibrary(key, language = 'ja', values = {}) {
  const message = messages[key]?.[normalizeLibraryLanguage(language) === 'en' ? 1 : 0] ?? key
  return String(message).replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match)
}
